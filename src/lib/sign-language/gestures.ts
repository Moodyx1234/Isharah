export function textToGestureTokens(text: string): string[] {
  const words = text.split(/\s+/);
  const tokens: string[] = [];
  for (const word of words) {
    const clean = word.replace(/[،,\.!؟?]/g, "").trim();
    const gestureId = WORD_TO_GESTURE[clean] || WORD_TO_GESTURE[clean.toLowerCase()];
    if (gestureId) {
      tokens.push(gestureId);
    } else {
      tokens.push("neutral");
    }
  }
  return tokens.filter((t, i, arr) => !(t === "neutral" && arr[i - 1] === "neutral"));
}
